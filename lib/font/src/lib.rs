//! PrettyBigRock's 5x9 bitmap font, the same one 1.x uses (a test checks every glyph against
//! `classic/tools/mkassets.py`, where it was drawn).
//!
//! A *bitmap font* stores each character as a small grid of dots instead of an outline, so
//! drawing text is just copying dots to the screen. A glyph here is [`HEIGHT`] rows of one byte
//! each; in a byte, bit 4 is the leftmost of the [`WIDTH`] dots and bit 0 the rightmost (bits 5
//! to 7 are always 0). A set bit is a dot of the text colour.
//!
//! The kernel's early text console and the console service both draw with it, so they show
//! the same letters. `#![no_std]` means this library uses only Rust's `core` library, not the
//! standard library (which needs an operating system underneath), so it builds for the kernel,
//! for programs and for the host.

#![no_std]

/// Glyph width in pixels.
pub const WIDTH: usize = 5;
/// Glyph height in pixels, including two rows for descenders (the tails of g, j, p, q and y).
pub const HEIGHT: usize = 9;

