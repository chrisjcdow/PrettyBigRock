/// The glyph for a character: the printable ASCII characters (space to `~`) have their own, and
/// anything else gives the glyph for `?`.
pub fn glyph(c: char) -> &'static [u8; HEIGHT] {
    let i = c as usize;
    if (32..127).contains(&i) { &GLYPHS[i - 32] } else { &GLYPHS[(b'?' - 32) as usize] }
}

// The tests use the standard library (`std`), which `#![no_std]` above leaves out of the
// library itself but which the host's test program may use.
#[cfg(test)]
extern crate std;

#[cfg(test)]
mod tests {
    use super::*;
    use std::process::Command;
    use std::string::String;
    use std::vec::Vec;

    #[test]
    fn anything_unprintable_is_a_question_mark() {
        let q = glyph('?');
        for c in ['\u{e9}', '\n', '\t', '\0', '\u{7f}', '\u{1f}', '\u{1F600}', char::MAX] {
            assert_eq!(glyph(c), q, "{c:?}");
        }
        assert_ne!(glyph('a'), q);
        assert_eq!(glyph(' '), &[0; HEIGHT]);
        // Both ends of the printable range have glyphs of their own.
        assert_eq!(glyph('~'), &GLYPHS[94]);
        assert_ne!(glyph('~'), q);
    }

    #[test]
    fn no_glyph_uses_the_unused_bits() {
        for (i, g) in GLYPHS.iter().enumerate() {
            assert!(g.iter().all(|row| row & 0xE0 == 0), "glyph {}", 32 + i);
        }
    }

    /// Every glyph is the one `classic/tools/mkassets.py` (the 1.x system's asset generator)
    /// makes. The script writes a C file; this reads the font table back out of it.
    #[test]
    fn every_glyph_matches_the_classic_font() {
        let script = concat!(env!("CARGO_MANIFEST_DIR"), "/../../classic/tools/mkassets.py");
        let dir = std::env::temp_dir().join(std::format!("pbr-font-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let out = dir.join("assets.c");
        // `-I` stops Python reading modules from the current folder.
        let run = match Command::new("python3").arg("-I").arg(script).arg(&out).output() {
            Ok(r) => r,
            Err(e) => {
                std::eprintln!("skipped: python3 is not available ({e})");
                let _ = std::fs::remove_dir_all(&dir);
                return;
            }
        };
        assert!(run.status.success(), "{}", String::from_utf8_lossy(&run.stderr));
        let c = std::fs::read_to_string(&out).unwrap();
        let _ = std::fs::remove_dir_all(&dir);

        let table = c.split("font_data[95][9] = {").nth(1).expect("the font table");
        let table = table.split("};").next().unwrap();
        let rows: Vec<Vec<u8>> = table
            .lines()
            .filter_map(|l| l.trim().strip_prefix('{'))
            .map(|l| {
                let numbers = l.split('}').next().unwrap();
                numbers
                    .split(',')
                    .map(|n| u8::from_str_radix(n.trim().trim_start_matches("0x"), 16).unwrap())
                    .collect()
            })
            .collect();
        assert_eq!(rows.len(), 95);
        for (i, row) in rows.iter().enumerate() {
            let c = char::from(32 + i as u8);
            assert_eq!(row.as_slice(), glyph(c).as_slice(), "the glyph for {c:?}");
        }
    }
}
