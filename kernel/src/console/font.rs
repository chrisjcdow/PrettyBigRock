/// The glyph for a character; anything outside printable ASCII shows as `?`.
pub fn glyph(c: char) -> &'static [u8; HEIGHT] {
    let i = c as usize;
    if (32..127).contains(&i) { &GLYPHS[i - 32] } else { &GLYPHS[(b'?' - 32) as usize] }
}
