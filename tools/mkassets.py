def main(out):
    o = ['/* Generated by tools/mkassets.py - do not edit */', '#include "kernel.h"', '']
    o.append('const u8 font_data[95][9] = {')
    for c in range(32, 127):
        rows = G[chr(c)]
        assert len(rows) <= 9, chr(c)
        rows = rows + ["....."] * (9 - len(rows))
        vals = []
        for r in rows:
            assert len(r) == 5, (chr(c), r)
            v = 0
            for i, ch in enumerate(r):
                if ch == '#':
                    v |= 1 << (4 - i)
            vals.append(v)
        o.append('  {' + ','.join('0x%02x' % v for v in vals) + '}, /* %r */' % chr(c))
    o.append('};')
    o.append('')
    o.append('const u32 icon_palette[%d] = {0,%s};' % (len(PKEYS) + 1, ','.join('0x%06x' % PAL[k] for k in PKEYS)))
    o.append('const u8 icon_data[%d][256] = {' % len(ICONS))
    for name, rows in ICONS:
        assert len(rows) == 16, name
        vals = []
        for r in rows:
            assert len(r) == 16, (name, r)
            for ch in r:
                vals.append(0 if ch == '.' else PKEYS.index(ch) + 1)
        o.append('  {' + ','.join(str(v) for v in vals) + '}, /* %s */' % name)
    o.append('};')
    o.append('')
    o.append('const char *cursor_data[%d] = {' % len(CURSOR))
    for r in CURSOR:
        assert len(r) == 12
        o.append('  "%s",' % r)
    o.append('};')
    open(out, 'w').write('\n'.join(o) + '\n')

main(sys.argv[1])
