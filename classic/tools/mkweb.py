"""Builds the browser player into build/web/: the page, a data file holding the disk image
and BIOS, and the v86 emulator core. Usage: mkweb.py <v86.wasm> <seabios.bin> <vgabios.bin>"""
import base64, os, shutil, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, 'build', 'web')
wasm, seabios, vgabios = sys.argv[1:4]
os.makedirs(out, exist_ok=True)

img = open(os.path.join(root, 'build', 'prettybigrock.img'), 'rb').read()
used = len(img.rstrip(b'\0'))
used = (used + 511) // 512 * 512  # only the sectors that hold something; the page pads the rest

def enc(b): return base64.b64encode(b).decode('ascii')
with open(os.path.join(out, 'data.js'), 'w') as f:
    f.write('/* PrettyBigRock disk image and BIOS, generated by tools/mkweb.py */\n')
    f.write('window.PBR_DATA = {\n')
    f.write('  image: "%s",\n' % enc(img[:used]))
    f.write('  seabios: "%s",\n' % enc(open(seabios, 'rb').read()))
    f.write('  vgabios: "%s"\n' % enc(open(vgabios, 'rb').read()))
    f.write('};\n')
shutil.copyfile(wasm, os.path.join(out, 'v86.wasm'))

page = open(os.path.join(root, 'web', 'player.html')).read()
# The artifact host adds its own skeleton; a stand-alone copy needs a full document.
open(os.path.join(out, 'player.html'), 'w').write(page)
standalone = ('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
              '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
              '<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}'
              'body{margin:0}[hidden]{display:none!important}</style>\n</head>\n<body>\n'
              + page + '\n</body>\n</html>\n')
open(os.path.join(out, 'index.html'), 'w').write(standalone)
print('web player built in build/web (image %d bytes)' % used)
